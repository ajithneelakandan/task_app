// A framework is a ready-made structure that helps developers build applications faster without creating everything from scratch.

// Why is Flutter called a Framework?

// Because it provides:

// ✅ Ready-made UI components (Widgets)
// ✅ Navigation between screens
// ✅ Animations
// ✅ Themes
// ✅ Icons
// ✅ State management support
// ✅ Access to device features (camera, GPS, etc.)
// ✅ Project structure

// Why is Flutter called a UI toolkit?

// Because its main purpose is to help you create beautiful user interfaces quickly by providing a rich set of pre-built widgets.

// Framework

// Provides the overall structure for building an app.
// Includes navigation, app lifecycle, project organization, state management support, and more.

// UI Toolkit

// Provides ready-made UI components for building screens.
// Includes widgets like buttons, text fields, images, icons, layouts, etc.

// Flutter is called both a framework and a UI toolkit because it not only gives you the ready-made UI parts (widgets),
// but also provides the overall structure and tools needed to build an entire application.

