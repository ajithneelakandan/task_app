// What is dart?
//          Dart is an open-source, object-oriented, general-purpose programming language developed by Google. 
// It is highly optimized for client development, making it the foundational language powering Google Flutter, 
// a popular UI toolkit used to build natively compiled mobile, web, and desktop applications from a single codebase
// Dart is a client-optimized, open-source programming language developed by Google that delivers excellent 
// multi-platform flexibility, high execution performance, and stellar developer productivity. It serves as
// the underlying foundation for the widely popular Flutter UI toolkit, which allows developers to build 
// beautiful apps across mobile, web, and desktop from a single codebase.The Dart programming language was 
//first unveiled on October 10, 2011, by Google. Internal development on the language originally began in 2010 
//October 2011: Publicly revealed at the GOTO Conference in Aarhus, Denmark.
//November 2013: Dart 1.0 was officially released as the first stable version.
//August 2018: Dart 2.0 was launched, featuring a sound type system and major optimization changes.

// What is Flutter?
//              Flutter is not actually a programming language; it is an open-source user interface (UI) software development toolkit 
// created by Google. Instead of writing code in a "Flutter language," developers write applications using Dart, which is the official
// programming language that powers the Flutter framework.Together, they allow you to build natively compiled applications for mobile (Android, iOS),
// web, and desktop (Windows, macOS, Linux) from a single codebase.

// The Core Language: DartSince Flutter apps are written entirely in Dart, understanding the language is key to understanding Flutter
// Object-Oriented: Dart is a class-based, object-oriented language. Its syntax feels very familiar if you already know Java, JavaScript, C#, 
// or C++.Two Compilation Modes: It uses Just-In-Time (JIT) compilation during development for instant code updates, and Ahead-Of-Time (AOT) 
// compilation to generate fast, native machine code for production releases.Productive and Safe: It features a flexible type system with 
// sound null safety, meaning the language helps you catch and prevent common app crashes before you launch.

// Why Developers Use Flutter?
//                     Flutter simplifies multi-platform development by acting as a comprehensive software development kit (SDK).
// Single Codebase: You write code once and deploy it to multiple operating systems. This slashes development time, lowers maintenance
// overhead, and eliminates the need for separate iOS and Android engineering teams.

// Stateful Hot Reload: This allows developers to modify source code and see the visual results instantly on an emulator or device without 
// losing the application's current state or waiting for a complete rebuild.

// Widget-Based Architecture: In Flutter, everything is a widget—from a structural layout to a simple button. It skips relying on the 
// device's native system buttons and menus. Instead, Flutter uses its own high-performance rendering engines, like Impeller or Skia, 
// to paint every pixel directly onto the screen, ensuring complete UI consistency across different devices.

// Pre-Built Design Libraries: It features robust, built-in design catalogs. These include Google's Material Design components and Apple’s 
// Cupertino widgets to seamlessly match target platform aesthetics out of the box.


